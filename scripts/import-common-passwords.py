"""Imports the bundled common-password blocklist, with provenance. Never edited by hand.

Source: SecLists, Passwords/Common-Credentials/10k-most-common.txt, MIT licensed, at a pinned
commit, with the downloaded file's SHA-256 pinned too: the script stops if either changes.
Output, byte-identical on every run:
  Sources/SwiftIdentity/Credential/CommonPasswordsList.swift   the entries, compiled in: one per
                                                               line of a raw string literal, in
                                                               source order, blank lines and
                                                               duplicates dropped
  scripts/COMMON-PASSWORDS.md                                  provenance

Compiled in rather than shipped as a resource: SwiftPM's generated `Bundle.module` accessor
stops the process when the bundle isn't beside the binary, and a deployment that copies only the
executable would crash on the first passphrase check.

Run from the package root:  python3 -I scripts/import-common-passwords.py
"""

import hashlib
import os
import sys
import urllib.request

COMMIT = "4c0fd59432ab8508edc23b3c880127edb12e34d5"
PATH = "Passwords/Common-Credentials/10k-most-common.txt"
URL = f"https://raw.githubusercontent.com/danielmiessler/SecLists/{COMMIT}/{PATH}"
SOURCE_SHA256 = "68782d6a4a19a4768d5f15dd66bd534e7a33055cc755411e33f16d18c50fdcce"
RETRIEVED = "2026-10-22"
SOURCE_OUT = os.path.join("Sources", "SwiftIdentity", "Credential", "CommonPasswordsList.swift")
PROVENANCE_OUT = os.path.join("scripts", "COMMON-PASSWORDS.md")


def main():
    with urllib.request.urlopen(URL, timeout=60) as response:
        data = response.read()
    digest = hashlib.sha256(data).hexdigest()
    if digest != SOURCE_SHA256:
        sys.exit(f"source changed: {digest} != {SOURCE_SHA256}")

    seen = set()
    entries = []
    for line in data.decode("utf-8").splitlines():
        entry = line.strip("\r\n")
        if entry and entry not in seen:
            seen.add(entry)
            entries.append(entry)

    for entry in entries:
        if '"#' in entry or not entry.isprintable():
            sys.exit(f"an entry can't go in a raw string literal: {entry!r}")
    listing = "\n".join(entries)
    out = (
        "// Generated by scripts/import-common-passwords.py. Do not edit; see scripts/COMMON-PASSWORDS.md.\n"
        "// SecLists, Passwords/Common-Credentials/10k-most-common.txt, MIT licensed,\n"
        "// Copyright (c) 2018 Daniel Miessler.\n\n"
        "/// The bundled common-password list, one entry per line, compiled in.\n"
        "enum CommonPasswordsList {\n"
        f"    /// {len(entries)} entries.\n"
        "    static let text = #\"\"\"\n"
        f"{listing}\n"
        "\"\"\"#\n"
        "}\n"
    ).encode("utf-8")
    with open(SOURCE_OUT, "wb") as handle:
        handle.write(out)

    script = open(__file__, "rb").read()
    provenance = f"""# Bundled common-password blocklist

`Sources/SwiftIdentity/Credential/CommonPasswordsList.swift`, read by `CommonPasswords`. Produced by
`scripts/import-common-passwords.py`; never edited by hand. Compiled in, not a resource bundle, so
a deployment that copies only its executable still has it.

- Source: SecLists `{PATH}`, commit `{COMMIT}`
  (<{URL}>), MIT licensed, Copyright (c) 2018 Daniel Miessler.
- Retrieved: {RETRIEVED}
- Source SHA-256: `{SOURCE_SHA256}`
- Stored file SHA-256: `{hashlib.sha256(out).hexdigest()}`, {len(entries)} entries
- Transformation: blank lines and duplicates dropped, order kept.
- Script SHA-256: `{hashlib.sha256(script).hexdigest()}`

Why this size: NIST SP 800-63B-4 §3.1.1.2 asks for a list "of sufficient size to prevent
subscribers from choosing passwords that attackers are likely to guess before reaching the
attempt limit", and warns that "excessively large blocklists are of little incremental security
benefit". The attempt limit here is 100.
"""
    with open(PROVENANCE_OUT, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(provenance)


if __name__ == "__main__":
    main()
